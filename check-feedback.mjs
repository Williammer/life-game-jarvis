import assert from 'node:assert/strict';
import {newDay,record} from './day-model.js';
import {newModules,gap,routes} from './module-model.js';
import {createPersonal,challenge,gates} from './journey.js';
import {reply,applyFeedback,undoFeedback,versions,feedbackKey} from './feedback.js';
let day=newDay(),modules=newModules();day.personal=createPersonal();day.moduleRoutes=routes(modules,day);
const descriptor=(scope,mid='',item='')=>({scope,mid,item});
const benchmark=descriptor('benchmark','running');
let p=reply(benchmark,'改用 Gary',day,modules).proposal;
assert.equal(modules[0].benchmark.id,'kipchoge');
assert.match(p.after,/Gary[\s\S]*差 1 次\/周/);
const before={day:structuredClone(day),modules:structuredClone(modules)};
({day,modules}=applyFeedback(p,day,modules));
assert.equal(modules[0].benchmark.id,'gary');assert.match(gap(modules[0],day).headline,/1 次\/周/);
assert.throws(()=>applyFeedback(p,day,modules),/过期/);
({day,modules}=undoFeedback({...before,version:versions(day,modules)},day,modules));
assert.equal(modules[0].benchmark.id,'kipchoge');
p=reply(descriptor('gap','running'),'马拉松成绩改为 4:10:00',day,modules).proposal;
assert.match(p.after,/4:10:00/);assert.equal(modules[0].metrics[2].value,14400);
({day,modules}=applyFeedback(p,day,modules));assert.equal(modules[0].metrics[2].value,15000);
assert.throws(()=>reply(descriptor('gap','running'),'成绩改为 4:99:00',day,modules),/核对/);
assert.throws(()=>reply(descriptor('gap','running'),'成绩改为 4',day,modules),/H:MM:SS/);
p=reply(descriptor('gap','running'),'马拉松成绩未知',day,modules).proposal;
({day,modules}=applyFeedback(p,day,modules));assert.equal(modules[0].metrics[2].value,null);assert.match(gap(modules[0],day).headline,/缺少/);
const route=descriptor('roadmap','agent','near');
p=reply(route,'近期改为先做只读提案',day,modules).proposal;
p=reply(route,'验收改为留下一个可复现的失败观察',day,modules,{proposal:p}).proposal;
assert.match(p.patch.roadmap[0].title,/只读/);assert.match(p.patch.roadmap[0].standard,/失败观察/);
({day,modules}=applyFeedback(p,day,modules));assert.match(modules[1].roadmap[0].title,/只读/);
p=reply(descriptor('plan'),'今天只有 45 分钟',day,modules).proposal;
assert.equal(day.core.budget,90);assert.equal(p.plan.context.budget,45);
({day,modules}=applyFeedback(p,day,modules));assert.equal(day.core.budget,45);assert.ok(day.events.some(e=>e.taskId));
p=reply(descriptor('context','agent','failure'),'背景改为最近已写好拒绝路径，但还没有重试测试',day,modules).proposal;
const previous=structuredClone(day);day.personal.revision++;
assert.throws(()=>applyFeedback(p,day,modules),/过期/);day=previous;
({day,modules}=applyFeedback(p,day,modules));assert.match(day.personal.facts.find(f=>f.id==='failure').text,/重试测试/);
assert.equal(reply(descriptor('metric','agent','approval'),'受控写入改为 1',day,modules).proposal,undefined);
assert.notEqual(feedbackKey({...descriptor('checkpoint','','agent-action'),detail:'a'}),feedbackKey({...descriptor('checkpoint','','agent-action'),detail:'b'}));
assert.equal(reply(descriptor('plan'),'我不赞同这个建议',day,modules).proposal,null);
const guard=versions(day,modules);day.core.reward='新奖励';assert.notEqual(versions(day,modules),guard);assert.throws(()=>undoFeedback({...before,version:guard},day,modules),/其他变更/);
assert.throws(()=>undoFeedback({...before,version:'old'},day,modules),/其他变更/);
day.core.active=['agent-action'];day.core.contracts={'agent-action':challenge('agent-action')};
day=record(day,{id:'agent-action',status:'done',checkpoints:challenge('agent-action').checkpoints.map(x=>x.id),evidence:'模拟的完整作品运行与拒绝断言',minutes:40},true);
assert.equal(gates(modules[1],day)[1].done,true);const xp=day.core.records['agent-action'].xp;
p=reply(descriptor('evidence','agent','agent-action'),'撤回能力验收',day,modules).proposal;
({day,modules}=applyFeedback(p,day,modules));assert.equal(day.core.records['agent-action'].proof,'self');assert.equal(day.core.records['agent-action'].xp,xp);assert.equal(gates(modules[1],day)[1].done,false);
assert.equal(feedbackKey(descriptor('evidence','agent','agent-action')),feedbackKey(descriptor('evidence','','agent-action')));
assert.equal(reply(descriptor('gap','agent','rubric'),'权重改为 2',day,modules).proposal,undefined);
assert.equal(reply(descriptor('benchmark','agent'),'榜样改为 Person javascript:alert(1)',day,modules).proposal,undefined);
console.log('Feedback check passed: references, baseline, negotiation, plan, versions, undo and evidence boundaries.');

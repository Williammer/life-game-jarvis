// One runnable check for the consequential rules in this throwaway simulator.
import assert from 'node:assert/strict';
import {fresh,act,scenario,progression,issues,totals} from './model.js';
let s=fresh();
assert.deepEqual(totals(s.draft),{minutes:80,energy:5,xp:75});
s=act(s,{type:'context',budget:60});
assert.ok(issues(s).length);
assert.equal(act(s,{type:'confirm'}).active.length,0,'over-budget draft cannot become active');
s=act(fresh(),{type:'confirm'});
const accepted=[...s.active];
s=act(s,{type:'disrupt'});
assert.deepEqual(s.active,accepted,'changes need confirmation');
assert.ok(!issues(s).length);
s=act(s,{type:'record',id:'build',status:'partial',proof:'checked',evidence:'已定位问题，待修复',minutes:0});
assert.equal(progression(s).xp,20);
assert.equal(s.records.build.minutes,0);
assert.deepEqual(progression(s).skills,['计算图解释'],'partial work does not prove mastery');
const valid={type:'record',id:'build',status:'done',proof:'checked',evidence:'模拟通过共享节点梯度累加'};
s=act(s,valid);s=act(s,valid);
assert.equal(progression(s).xp,40,'repeated save awards once');
assert.equal(progression(s).skills.length,2);
s=act(s,{type:'confirm'});
assert.deepEqual(s.active,['recover','review','family']);
assert.equal(progression(s).xp,40,'changing plans preserves history');
s=act(s,{type:'record',id:'run',status:'done',evidence:'不在计划中'});
assert.equal(progression(s).xp,40);
s=act(s,{type:'record',id:'review',status:'done',proof:'checked',evidence:'模拟数值核验通过'});
assert.equal(progression(s).skills.length,3);
s=act(s,{type:'claim'});
assert.equal(s.claimed,true);
assert.equal(act(s,{type:'claim'}).claimed,true);
s=act(s,{type:'removeRecord',id:'build'});
assert.equal(progression(s).skills.length,1,'dependent evidence locks again after correction');
assert.equal(progression(s).xp,25);
assert.equal(s.claimed,true,'reward history remains explicit after correction');
assert.equal(progression(scenario('缺少能力证据')).skills.length,1);
assert.equal(progression(scenario('结算样例')).skills.length,2);
assert.equal(progression(fresh()).gap,7131);
assert.equal(progression(act(fresh(),{type:'measurement'})).gap,6831);
assert.equal(act(fresh(),{type:'record',id:'build',evidence:'ok'}).records.build,undefined);
assert.equal(act(act(fresh(),{type:'confirm'}),{type:'record',id:'build',evidence:' '}).records.build,undefined);
assert.ok(issues(scenario('低精力')).length===0);
console.log('PASS: confirmation, budgets, partial progress, evidence prerequisites, corrections, duplicate XP, rewards, measurements.');

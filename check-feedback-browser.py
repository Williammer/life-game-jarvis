"""Object-scoped discussion checks. Requires agent-browser and serve.py on 5180."""
import json
import subprocess

SESSION = 'jarvis-feedback-check'
COUNT = 0

def browser(*args):
    result = subprocess.run(['agent-browser', '--session', SESSION, *args], capture_output=True, text=True, timeout=20)
    assert result.returncode == 0, result.stderr or result.stdout
    return result.stdout.strip()

def click(selector):
    browser('scrollintoview', selector)
    browser('click', selector)

def read(selector):
    return browser('get', 'text', selector)

def evaluate(source):
    return json.loads(browser('eval', source))

def check(condition, name):
    global COUNT
    assert condition, name
    COUNT += 1
    print(f'PASS {COUNT}: {name}', flush=True)

def send(text):
    browser('fill', '#feedback-message', text)
    click('#feedback-form [type=submit]')

def close():
    click('[data-feedback-control=close]')

